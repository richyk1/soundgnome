#!/usr/bin/env node
// Builds src/lib/pixel-icons.css: one CSS mask class per pixel icon the app uses.
// Markup: <i class="pxi pxi-play" aria-hidden="true"></i>. Add a name below, then rerun.

import fs from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const svgDir = path.join(root, 'node_modules/pixelarticons/svg')
const outFile = path.join(root, 'src/lib/pixel-icons.css')

// pixelarticons names (MIT, https://github.com/halfmage/pixelarticons).
const ICONS = [
  'album', 'arrow-down', 'arrow-left', 'arrow-right', 'arrow-up', 'audio-waveform', 'bell',
  'bulletlist', 'calendar', 'check', 'checkbox-on', 'chevron-down', 'chevron-left', 'chevron-right',
  'chevron-up', 'circle-info', 'circle-question', 'clock', 'close', 'cloud', 'copy', 'database',
  'download', 'external-link', 'eye', 'eye-off', 'file', 'filter', 'flag', 'folder', 'gear',
  'grid-2x2-2', 'headphone', 'heart', 'home', 'hourglass', 'image', 'keyboard', 'library', 'link',
  'list-box', 'loader', 'lock', 'menu', 'mic', 'minus', 'more-horizontal', 'music',
  'pencil', 'plug', 'plus', 'radio', 'redo', 'refresh', 'reload', 'save', 'search',
  'server', 'shuffle', 'sliders-vertical', 'sort-vertical', 'sparkles', 'square-alert',
  'thumbs-down', 'thumbs-up', 'trash', 'undo', 'unlink', 'upload', 'user', 'users', 'volume-1',
  'volume-2', 'volume-3', 'volume-x', 'warning-diamond', 'youtube',
]

// Class name → a different pixelarticons file: transport controls use solid glyphs.
const ALIASES = {
  pause: 'pause-solid',
}

// Drawn on the same 24-unit grid with 2-unit pixels: the set ships no skip
// glyphs and only an outlined play, which reads lighter than solid pause.
const CUSTOM = {
  play: 'M7 3h2v18H7zm2 2h2v14H9zm2 2h2v10h-2zm2 2h2v6h-2zm2 2h2v2h-2z',
  'skip-forward': 'M6 5h2v14H6zm2 2h2v2H8zm2 2h2v2h-2zm2 2h2v2h-2zm-2 2h2v2h-2zm-2 2h2v2H8zm8-10h2v14h-2z',
  'skip-back': 'M16 5h2v14h-2zm-2 2h2v2h-2zm-2 2h2v2h-2zm-2 2h2v2h-2zm2 2h2v2h-2zm2 2h2v2h-2zM6 5h2v14H6z',
}

function dataUri(paths) {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' shape-rendering='crispEdges'>${paths}</svg>`
  return `url("data:image/svg+xml,${svg.replace(/"/g, "'").replace(/#/g, '%23').replace(/</g, '%3C').replace(/>/g, '%3E')}")`
}

async function iconPaths(name) {
  const svg = await fs.readFile(path.join(svgDir, `${name}.svg`), 'utf8')
  const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"[^>]*>/g)].map((m) => `<path d='${m[1]}'/>`)
  if (paths.length === 0) throw new Error(`No <path> in pixelarticons/${name}.svg`)
  return paths.join('')
}

const rules = []
for (const name of ICONS) rules.push(`.pxi-${name} { --pxi: ${dataUri(await iconPaths(name))}; }`)
for (const [name, source] of Object.entries(ALIASES)) rules.push(`.pxi-${name} { --pxi: ${dataUri(await iconPaths(source))}; }`)
for (const [name, d] of Object.entries(CUSTOM)) rules.push(`.pxi-${name} { --pxi: ${dataUri(`<path d='${d}'/>`)}; }`)

const css = `/* Generated by scripts/generate-pixel-icons.mjs. Do not edit by hand. */
.pxi {
  display: inline-block;
  inline-size: 1em;
  block-size: 1em;
  flex: none;
  vertical-align: -0.125em;
  background-color: currentColor;
  -webkit-mask: var(--pxi) center / 100% 100% no-repeat;
  mask: var(--pxi) center / 100% 100% no-repeat;
}
@media (forced-colors: active) {
  .pxi { forced-color-adjust: none; }
}
${rules.join('\n')}
`

await fs.writeFile(outFile, css)
console.log(`✓ Generated ${path.relative(root, outFile)} (${rules.length} icons)`)
